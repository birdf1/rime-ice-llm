def _parse(block: str) -> list[str]:
    """
    把三引号词表解析成列表。

    ⚠️ 必须逐行过滤注释：
       词表里用「# 电机与拖动」这种分组标题做可读性注释，
       如果直接 .split()，'#' 后面的中文会被当成词条塞进词库
       （曾因此生成出「与自动化」「精度与制图」这类碎片）。
    """
    if isinstance(block, list):      # 容错：万一又写回 .split()
        block = "`n".join(block)
    out: list[str] = []
    seen: set[str] = set()
    for line in block.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        for w in line.split():
            if not w or w.startswith("#") or w in seen:
                continue
            seen.add(w)
            out.append(w)
    return out


